import assert from 'node:assert/strict';
import { blankProject, blankState } from '../modules/state.js';
import { createPortfolioEngine } from '../modules/portfolio.js';
import { buildHomeMetrics, nextMilestone, dividendGoalStatus } from '../modules/home-metrics.js';

const state=blankState(),project=state.projects[0];
project.id='p-msty'; project.targetUnits=1000; project.distributionFrequency='weekly';
state.trades.push({id:'t1',projectId:project.id,date:'2026-01-02',type:'buy',buyType:'direct',shares:200,price:10});
['2026-07-24','2026-07-31','2026-08-07','2026-08-14','2026-08-21','2026-08-28','2026-09-04','2026-09-11'].forEach((date,index)=>state.dividends.push({id:`d${index}`,projectId:project.id,date,amountUSD:50,sharesAtPayment:200}));
const engine=createPortfolioEngine(()=>state,()=>project.id),calc=engine.computeProject(project);
const emptyProject=blankProject('CONY','CONY Fund'); emptyProject.id='p-cony'; emptyProject.targetUnits=500; state.projects.push(emptyProject);
const emptyCalc=engine.computeProject(emptyProject);
const milestone=nextMilestone(calc);
assert.equal(milestone.shares,250);
assert.equal(milestone.remaining,50);
assert.equal(nextMilestone({...calc,shares:250}).shares,500,'250주 달성 즉시 다음 목표는 500주여야 함');
const metrics=buildHomeMetrics([calc,emptyCalc],state.dividends,new Date('2026-09-13T12:00:00'));
assert.equal(metrics.month.actual,100);
assert.equal(metrics.month.remaining,0);
assert.equal(metrics.month.total,metrics.month.actual);
assert.equal(metrics.year.total,metrics.year.actual);
assert.equal(metrics.months.length,12);
assert.ok(metrics.years.length>=1);
assert.equal(metrics.nextDividend,null);
assert.deepEqual(metrics.forecast,[]);
assert.equal(metrics.nextGoal.milestone.shares,250);
assert.equal(metrics.nextGoal.calc.project.symbol,'MSTY');
assert.equal(metrics.projectMonth.length,1);
assert.equal(metrics.projectMonth[0].symbol,'MSTY');
assert.equal(metrics.projectMonth[0].actual,100);
assert.equal(metrics.pace.monthly,300/3,'recent three-month average must use actual deposits only');
assert.equal(metrics.pace.annualized,1200);
console.log('DividendOS v0.11.3 home metrics QA: PASS');

const settings={...state.settings,exchangeRate:1300,targetMonthlyDividend:500,warningKRW:18000000,thresholdKRW:20000000};
assert.equal(dividendGoalStatus(settings,250,0).monthPct,50);
assert.equal(dividendGoalStatus(settings,750,0).monthRemaining,0);
assert.equal(dividendGoalStatus({...settings,targetMonthlyDividend:0},0,0).monthPct,null);
assert.equal(dividendGoalStatus(settings,0,18000000/1300).alert,'early');
assert.equal(dividendGoalStatus(settings,0,20000000/1300).alert,'reached');
assert.equal(dividendGoalStatus({...settings,dividendAlertEnabled:false},0,99999).alert,'off');
assert.equal(dividendGoalStatus({...settings,warningKRW:0},0,0).alert,'normal');
assert.equal(dividendGoalStatus({...settings,warningKRW:25000000},0,19000000/1300).alert,'normal');
// Completed calendar months only; the unfinished current month cannot skew growth.
const history=Array.from({length:7},(_,i)=>({id:'pace-'+i,projectId:project.id,date:`2026-${String(i+4).padStart(2,'0')}-01`,amountUSD:i===6?99999:i<3?100:200}));
const completed=buildHomeMetrics([],history,new Date('2026-10-18T12:00:00'));
assert.equal(completed.pace.monthly,200);assert.equal(completed.pace.change,100);
assert.equal(completed.pace.recentFrom,'2026-07');assert.equal(completed.pace.recentTo,'2026-09');
assert.equal(completed.pace.previousFrom,'2026-04');assert.equal(completed.pace.previousTo,'2026-06');
assert.equal(buildHomeMetrics([],history.slice(4),new Date('2026-10-18T12:00:00')).pace.available,false);
assert.equal(buildHomeMetrics([],history.slice(2),new Date('2026-10-18T12:00:00')).pace.change,null);
assert.equal(buildHomeMetrics([],history.slice(0,3),new Date('2026-10-18T12:00:00')).pace.monthly,0);
console.log('Completed-month pace PASS: current month excluded, dates explicit, short history suppressed');
